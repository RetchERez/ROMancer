"""Write romancer/core_pins_linux.py and cores/CORE-ORIGINS.json for a staged Linux engine folder.

Usage: python3 linux/write_linux_pins.py <repo> <staged-cores-dir>

Source, commit, license, options and ROMancer patch metadata are taken unchanged
from the Windows pins (both platforms build the same CORE-SOURCES.zip); only the
library file names and identities differ.
"""
import hashlib
import importlib.util
import json
from pathlib import Path
import pprint
import sys

repo, cores = Path(sys.argv[1]), Path(sys.argv[2])
spec = importlib.util.spec_from_file_location('win_pins', repo / 'romancer/core_pins.py')
win = importlib.util.module_from_spec(spec)
spec.loader.exec_module(win)
WINDOWS = win.WINDOWS_CORE_PINS


def sha(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


pins = {}
for engine, pin in WINDOWS.items():
    name = pin['file'].removesuffix('.dll') + '.so'
    library = cores / name
    if not library.is_file():
        raise SystemExit(f'missing {name}')
    pins[engine] = {**pin, 'file': name, 'sha256': sha(library)}

(cores / 'CORE-ORIGINS.json').write_text(json.dumps(pins, indent=2) + '\n', encoding='utf-8')

files = {}
for path in sorted(cores.rglob('*')):
    if path.is_file():
        files[path.relative_to(cores).as_posix()] = {'size': path.stat().st_size, 'sha256': sha(path)}

target = repo / 'romancer/core_pins_linux.py'
target.write_text(
    '"""Reviewed Linux x86-64 engines: same pinned sources as the Windows build, built with\n'
    'linux/build_cores_linux.sh. Generated by linux/write_linux_pins.py; do not edit."""\n'
    'CORE_PINS = ' + pprint.pformat(pins, width=100, sort_dicts=True) + '\n'
    'CORE_FILES = ' + pprint.pformat(files, width=100, sort_dicts=True) + '\n',
    encoding='utf-8', newline='\n')
print(f'wrote {target} ({len(pins)} engines, {len(files)} files)')
