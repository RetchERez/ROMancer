"""Apply ROMancer provenance hooks to a pristine FCEUmm source tree (argv[1]).

All edits are prepared in memory and written only when every anchor matched
exactly the expected number of times; an already patched tree is refused.

Domains (tags are ROM file offsets after the 16-byte iNES header; a 512-byte
trainer counts as ROM data in front of PRG, CHR-ROM follows PRG):

  palette  32   PPU palette $3F00-$3F1F, raw NES color indexes. Entries
                 0/4/8/C of both halves all report the backdrop cell ($3F00,
                 mirrored at $3F10) and carry its tag: that is the color shown
                 there. The hidden cells $3F04/08/0C are not exposed (never
                 displayed, and not part of FCEUmm savestates). Data is a
                 mirror kept current on every palette write, power-on, state
                 load and frame end.
  vram     2K   CIRAM / NTARAM (nametables + attribute tables)
  vram4    2K   4-screen extra nametable RAM (only for 4-screen carts)
  oam      256  SPRAM ($2004 writes and $4014 DMA; DMA keeps source tags)
  wram     2K + cart work RAM: [0,0x800) is CPU RAM $0000-$07FF, the rest is
                 the PRG-RAM/SRAM chip (mapper chip 0x10, at most 64 KB).
                 Tags are live; the data mirror is refreshed every frame.
  chr      CHR-RAM chip (carts that have one; index = offset in the chip,
                 equal to the PPU address for an unbanked 8 KB chip)
  chr_map  8    one entry per 1 KB PPU pattern slot $0000-$1FFF: RT_ROM tag
                 of the CHR-ROM offset mapped there (RT_NONE for CHR-RAM),
                 kept current on every CHR bank switch (pc = instruction that
                 switched) and re-synced at the end of each frame; data NULL.

CPU reads resolve through Page[] (the table every mapper's setprg* fills), so
PRG offsets are right for any mapper whose read handler returns Page[] data;
a read whose value disagrees with Page[] is left untagged.
"""
import sys
from pathlib import Path

base = Path(sys.argv[1])
root = base / 'src'
FILES = {}  # path -> text; written at the very end


def load(p):
    if p not in FILES:
        if not p.is_file():
            raise SystemExit(f'{p}: missing')
        t = p.read_text(encoding='utf-8', newline='')
        if 'ROMANCER_TRACE' in t or 'romancer_' in t:
            raise SystemExit(f'{p}: already patched; restore the pristine source first')
        FILES[p] = t
    return FILES[p]


def edit(rel, old, new, count=1):
    p = (root / rel).resolve()
    t = load(p)
    if '\r\n' in t:
        old, new = old.replace('\n', '\r\n'), new.replace('\n', '\r\n')
    if t.count(old) != count:
        raise SystemExit(f'{rel}: expected {count} of {old!r}, found {t.count(old)}')
    FILES[p] = t.replace(old, new)


for stale in ('romancer_fceumm.h', 'romancer_fceumm.c'):
    if (root / stale).exists():
        raise SystemExit(f'{stale}: already present; restore the pristine source first')

