import assert from 'node:assert/strict';
import {shortcutFor,historyAction,rememberEditor,SHORTCUTS} from '../romancer/ui/shortcuts.js';
const event=(key,extra={})=>({key,ctrlKey:false,shiftKey:false,altKey:false,metaKey:false,target:{closest:()=>null},...extra});
assert.equal(shortcutFor(event('s',{ctrlKey:true})),'save');
assert.equal(shortcutFor(event('z',{ctrlKey:true})),'undo');
assert.equal(shortcutFor(event('Z',{ctrlKey:true,shiftKey:true})),'redo');
assert.equal(shortcutFor(event('y',{ctrlKey:true})),'redo');
assert.equal(shortcutFor(event('k',{ctrlKey:true})),'search');
assert.equal(shortcutFor(event('?',{shiftKey:true})),'help');
const input={closest:()=>({})};
assert.equal(shortcutFor(event('z',{ctrlKey:true,target:input})),null,'Text fields retain native undo.');
assert.equal(shortcutFor(event('?',{target:input})),null);
assert.equal(shortcutFor(event('s',{ctrlKey:true}),{gameFocused:true}),null);
assert.equal(shortcutFor(event('s',{ctrlKey:true}),{modalOpen:true}),null);
for(const extra of [{metaKey:true},{altKey:true},{isComposing:true},{repeat:true},{defaultPrevented:true}])assert.equal(shortcutFor(event('s',{ctrlKey:true,...extra})),null);
for(const key of ['w','l','n','p','Escape','F4','Delete'])assert.equal(shortcutFor(event(key,{ctrlKey:true})),null);
const available=new Set(['sprite-undo','pixel-undo','levels-redo']);
assert.equal(historyAction('assets','sprite-canvas',-1,a=>available.has(a)),'sprite-undo');
assert.equal(historyAction('assets','paint-canvas',-1,a=>available.has(a)),'pixel-undo');
assert.equal(historyAction('assets','map-canvas',-1,a=>available.has(a)),'draft-undo');
assert.equal(historyAction('levels','level-canvas',1,a=>available.has(a)),'levels-redo');
assert.equal(historyAction('levels','field',-1,()=>true),'draft-undo','A field edit must not undo a room stroke.');
assert.equal(historyAction('resources','',1,()=>false),'draft-redo');
const state={historyEditor:'sprite-canvas'};let refreshed=0,canUndo=false;
rememberEditor(state,{target:{closest:s=>s==='canvas'?{id:'paint-canvas'}:null}},()=>{refreshed++;canUndo=historyAction('assets',state.historyEditor,-1,a=>a==='pixel-undo')==='pixel-undo';});
assert.equal(canUndo,true);assert.equal(refreshed,1,'Changing editors must refresh footer availability immediately.');
assert.ok(SHORTCUTS.length<=7);
assert.ok(SHORTCUTS.every(row=>!row[0].includes('Win')&&!row[0].includes('Alt')));
console.log('Scoped shortcuts preserve Windows keys, typing, composition, dialogs and game input; undo targets the active editor.');

assert.equal(historyAction('levels','maps-edit',-1,a=>a==='maps-undo'),'maps-undo');
assert.equal(historyAction('levels','maps-edit',1,a=>a==='maps-redo'),'maps-redo');
