import assert from 'node:assert/strict';
const tools=await import('../romancer/ui/pixel_tools.js').catch(()=>null);
assert.ok(tools,'validated pixel transform tools are missing');
const original=[1,2,3,4,5,6,7,8,9];
assert.deepEqual(tools.transformPixels(original,3,3,'flip-x',0,16),[3,2,1,6,5,4,9,8,7]);
assert.deepEqual(tools.transformPixels(original,3,3,'flip-y',0,16),[7,8,9,4,5,6,1,2,3]);
const rotated=tools.transformPixels(original,3,3,'rotate-cw',0,16);
assert.deepEqual(rotated,[7,4,1,8,5,2,9,6,3]);
assert.deepEqual(tools.transformPixels(rotated,3,3,'rotate-ccw',0,16),original);
assert.deepEqual(tools.transformPixels(original,3,3,'fill',5,16),Array(9).fill(5));
assert.deepEqual(tools.transformPixels(original,3,3,'clear',0,16),Array(9).fill(0));
assert.deepEqual(original,[1,2,3,4,5,6,7,8,9]);
assert.throws(()=>tools.transformPixels([0,1],2,1,'rotate-cw',0,4),/square/i);
assert.throws(()=>tools.transformPixels([0,1],2,1,'fill',4,4),/palette/i);
const clipboard=tools.copyTile(original,3,3,16);assert.deepEqual(tools.pasteTile(clipboard,3,3,16),original);
clipboard.pixels[0]=0;assert.equal(original[0],1);
assert.throws(()=>tools.pasteTile(clipboard,3,3,4),/palette/i);
assert.throws(()=>tools.pasteTile(clipboard,8,8,16),/dimension/i);
assert.equal(typeof tools.mergeCellChanges,'function','switching tiles needs a source-preserving staged-cell merge');
const palette={kind:'palette',palette_id:'colors',index:0},oldCell={kind:'cell',bitmap_id:'tiles',cell_index:0,before_pixels:[0,0],after_pixels:[1,0]};
const newCell={...oldCell,after_pixels:[0,1]};
const merged=tools.mergeCellChanges([palette,oldCell],[newCell]);
assert.deepEqual(merged,[palette,newCell]);assert.deepEqual(oldCell.after_pixels,[1,0]);
assert.deepEqual(tools.mergeCellChanges(merged,[{...newCell,after_pixels:[0,0]}]),[palette]);
console.log('Literal fill, clear, flips, rotations, clipboard isolation and palette bounds passed.');
